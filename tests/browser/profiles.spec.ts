test('stale tab cannot overwrite; tab selection cannot retarget another tab draft', async ({ page, context }) => {
  await openSettings(page)
  const other = await context.newPage()
  await openSettings(other)
  await nameInput(other).fill('Unsaved in other tab')
  await nameInput(page).fill('Ada')
  await save(page)
  await other.getByRole('button', { name: 'Save profile', exact: true }).click()
  await expect(other.getByRole('alert')).toContainText('changed in another tab')
  await expect(nameInput(other)).toHaveValue('Unsaved in other tab')
  await page.getByLabel('New profile name').fill('Bea')
  await page.getByRole('button', { name: 'Create profile', exact: true }).click()
  await expect(nameInput(page)).toHaveValue('Bea')
  await expect(other.getByLabel('Active profile')).not.toHaveValue(await page.getByLabel('Active profile').inputValue())
  other.once('dialog', (dialog) => dialog.accept())
  await other.getByRole('button', { name: 'Reload saved profile' }).click()
  await expect(nameInput(other)).toHaveValue('Ada')
  await nameInput(other).fill('Updated Ada')
  await save(other)
  await expect(nameInput(page)).toHaveValue('Bea')
})

test('failed writes retain form input and successful retry persists it', async ({ page }) => {
  await openSettings(page)
  await nameInput(page).fill('Recoverable input')
  await page.evaluate(() => {
    const original = IDBObjectStore.prototype.put
    ;(window as unknown as { restoreWrite: () => void }).restoreWrite = () => { IDBObjectStore.prototype.put = original }
    IDBObjectStore.prototype.put = function (...args) {
      if (this.name === 'profiles') throw new DOMException('Simulated disk full', 'QuotaExceededError')
      return original.apply(this, args)
    }
  })
  await page.getByRole('button', { name: 'Save profile', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('Simulated disk full')
  await expect(nameInput(page)).toHaveValue('Recoverable input')
  await expect(page.getByText('Profile saved.', { exact: true })).toHaveCount(0)
  await page.evaluate(() => (window as unknown as { restoreWrite: () => void }).restoreWrite())
  await save(page)
  await page.reload()
  await expect(nameInput(page)).toHaveValue('Recoverable input')
})

test('unavailable IndexedDB shows retry without reporting an empty workspace', async ({ page }) => {
  await page.addInitScript(() => { IDBFactory.prototype.open = () => { throw new DOMException('Storage denied', 'SecurityError') } })
  await page.goto('./')
  await expect(page.getByRole('heading', { name: 'Browser storage unavailable' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Retry storage' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Settings', exact: true })).toHaveCount(0)
})

test('switching with an unsaved form requires confirmation and cannot copy it to another profile', async ({ page }) => {
  await openSettings(page)
  await page.getByLabel('New profile name').fill('Ada')
  await page.getByRole('button', { name: 'Create profile', exact: true }).click()
  await expect(nameInput(page)).toHaveValue('Ada')
  await page.getByLabel('Active profile').selectOption({ label: 'Guest' })
  await expect(nameInput(page)).toHaveValue('')
  await nameInput(page).fill('Uncommitted Guest name')
  page.once('dialog', (dialog) => dialog.dismiss())
  await page.getByLabel('Active profile').selectOption({ label: 'Ada' })
  await expect(nameInput(page)).toHaveValue('Uncommitted Guest name')
  page.once('dialog', (dialog) => dialog.accept())
  await page.getByLabel('Active profile').selectOption({ label: 'Ada' })
  await expect(nameInput(page)).toHaveValue('Ada')
  await page.getByLabel('Age (optional)').fill('25')
  await save(page)
  await page.getByLabel('Active profile').selectOption({ label: 'Guest' })
  await expect(nameInput(page)).toHaveValue('')
  await expect(page.getByLabel('Age (optional)')).toHaveValue('')
})
