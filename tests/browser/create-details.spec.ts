test.setTimeout(90000)
const b = (p: Page, name: string) => p.getByRole('button', { name, exact: true })
const f = (p: Page, name: string) => p.getByLabel(name, { exact: true })
const card = (p: Page) => p.getByRole('article', { name: 'Modal squat', exact: true }).getByRole('button')
const instructions = '<b>Plain instructions</b>\n' + Array.from({ length: 30 }, (_, i) => `Instruction line ${i + 1}`).join('\n')
const note = 'Library note only\nSecond note line <script>inert</script>'
async function rows(p: Page, store: string) {
  return p.evaluate(async (store) => {
    const db = await new Promise<IDBDatabase>((resolve, reject) => { const r = indexedDB.open('boros'); r.onsuccess = () => resolve(r.result); r.onerror = () => reject(r.error) })
    try { return await new Promise<any[]>((resolve, reject) => { const r = db.transaction(store).objectStore(store).getAll(); r.onsuccess = () => resolve(r.result); r.onerror = () => reject(r.error) }) } finally { db.close() }
  }, store)
}
async function title(p: Page, text: string) {
  await expect(p.getByRole('heading', { level: 1 })).toHaveCount(1)
  await expect(p.getByRole('heading', { level: 1 })).toHaveText(text)
  await expect(p.getByRole('navigation', { name: 'Editor breadcrumbs' })).toHaveCount(0)
  await expect(p.getByRole('button', { name: /^Back to (Create|Plan|AI)$/ })).toHaveCount(0)
  await expect(p.locator('h1 button, h1 a')).toHaveCount(0)
}
async function setup(p: Page) {
  await p.goto('./'); await b(p, 'Create').click()
  if (await b(p, 'Understood').isVisible()) await b(p, 'Understood').click()
  await b(p, 'Create exercise').click(); await f(p, 'Exercise name').fill('Modal squat'); await f(p, 'Set 1 Reps minimum').fill('8')
  await f(p, 'Instructions (optional)').fill(instructions); await f(p, 'Notes (optional)').fill(note)
  await f(p, 'YouTube tutorial URL (optional)').fill('https://youtu.be/M7lc1UVf-VE?autoplay=1&note=private')
  await b(p, 'Save').click(); await expect(card(p)).toBeVisible()
  await b(p, 'Create Plan').click(); await f(p, 'Plan name').fill('Independent plan'); await f(p, 'Duration (weeks)').fill('4')
  await b(p, 'Add exercise').click(); await b(p, 'Add Modal squat').click(); await b(p, 'Save plan').click()
  await expect(p.getByRole('article', { name: 'Plan Independent plan', exact: true })).toBeVisible()
}

