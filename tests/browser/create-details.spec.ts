test('invalid saved tutorial never mounts a player; blocked embed leaves details and Close available', async ({ page, context }) => {
  await setup(page)
  await page.evaluate(async () => {
    const db = await new Promise<IDBDatabase>((resolve) => { const r = indexedDB.open('boros'); r.onsuccess = () => resolve(r.result) })
    await new Promise<void>((resolve, reject) => { const tx = db.transaction('exercises', 'readwrite'), store = tx.objectStore('exercises'); const r = store.getAll(); r.onsuccess = () => { store.put({ ...r.result[0], tutorialUrl: 'https://evil.test/embed/abcdefghijk' }) }; tx.oncomplete = () => resolve(); tx.onabort = () => reject(tx.error) }); db.close()
  })
  await page.reload(); await card(page).click(); await expect(page.locator('iframe')).toHaveCount(0); await b(page, 'Close').click()
  await cardAction(page, page.getByRole('article', { name: 'Modal squat', exact: true }), 'Edit')
  await f(page, 'YouTube tutorial URL (optional)').fill('https://youtu.be/M7lc1UVf-VE'); await b(page, 'Save').click()
  await page.route('https://www.youtube.com/embed/**', (route) => route.abort('failed'))
  await card(page).click(); await expect(page.getByRole('region', { name: 'Note', exact: true })).toContainText(note)
  await b(page, 'Close').click(); await expect(card(page)).toBeFocused(); await expect(page.locator('iframe')).toHaveCount(0)
  expect(context.pages()).toHaveLength(1)
})
